package entity;

/**
 * Defines math operators for calculator.
 */
public enum Operator {

    /** Addition. */
    ADD,

    /** Subtraction. */
    SUBTRACT,

    /** Multiplication. */
    MULTIPLY,

    /** Division. */
    DIVIDE,

    /** Exponentiation. */
    EXPONENT,

    /** Equals sign to end calculation. */
    EQUAL
}
